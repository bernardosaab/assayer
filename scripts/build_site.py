"""Build the static demo site: run every eval offline and write one report per run.

Used by CI (artifact) and the Pages workflow. Deterministic and free: the fake profile only.

    uv run python scripts/build_site.py --out site
"""

from __future__ import annotations

import argparse
import html
import shutil
import subprocess
import sys
from pathlib import Path

EVALS = [
    ("resume_extraction", "Single-step extraction with gold labels, traps and an LLM judge"),
    ("posting_extraction", "A second extraction eval defined in YAML only"),
    (
        "hr_assistant",
        "Multi-turn tool-using agent with a simulated user, chaos and injection cases",
    ),
]


def assayer(*args: str) -> None:
    subprocess.run([sys.executable, "-m", "assayer", *args], check=True)  # noqa: S603


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path("site"))
    args = parser.parse_args()
    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    for name, blurb in EVALS:
        run_id = f"demo-{name}"
        assayer("run", name, "--run-id", run_id, "--repeats", "1")
        assayer("report", run_id, "-o", str(out / f"{name}.html"))
        rows.append((name, blurb))

    explainer = Path("docs/site/how-it-works.html")
    if explainer.exists():
        shutil.copy(explainer, out / explainer.name)

    live = Path("docs/demo/reports")
    live_links = []
    if live.exists():
        for report in sorted(live.glob("*.html")):
            shutil.copy(report, out / report.name)
            live_links.append(report.name)

    items = "\n".join(
        f'<li><a href="{html.escape(n)}.html"><code>{html.escape(n)}</code></a> '
        f"<span>{html.escape(b)}</span></li>"
        for n, b in rows
    )
    live_items = (
        "\n".join(
            f'<li><a href="{html.escape(n)}"><code>{html.escape(n)}</code></a></li>'
            for n in live_links
        )
        or "<li><span>None committed yet.</span></li>"
    )
    (out / "index.html").write_text(
        f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Assayer demo reports</title>
<style>
:root {{ --bg:#f7f7f5; --text:#1d1d1f; --muted:#6b6b70; --accent:#2f5bd3; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg:#141416; --text:#ececee; --muted:#9a9aa2; --accent:#8fa8ff; }} }}
body {{ margin:0; background:var(--bg); color:var(--text); font:16px/1.6 system-ui, sans-serif; }}
main {{ max-width:760px; margin:0 auto; padding:40px 16px; }}
a {{ color:var(--accent); }} li {{ margin:10px 0; }} span, p {{ color:var(--muted); }}
</style></head><body><main>
<h1>Assayer demo reports</h1>
<p><a href="how-it-works.html">How it works: one attempt from claim to grade</a></p>
<p>Generated by CI on every push to main. The offline runs use the scripted fake provider, so they are
deterministic and free; their failures are deliberate and show the harness catching them.</p>
<h2>Offline (scripted models)</h2><ul>{items}</ul>
<h2>Real local model (Ollama, measured), committed</h2>
<p>llama3.2:3b as the agent, qwen2.5:7b as the judge, on a laptop GPU. Each version is one step of the
hill-climbing loop described in docs/hill-climbing.md.</p><ul>{live_items}</ul>
</main></body></html>
""",
        encoding="utf-8",
    )
    print(f"site written to {out}")


if __name__ == "__main__":
    main()
